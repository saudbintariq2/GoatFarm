using GoatFarm.Application.Common;
using GoatFarm.Application.ViewModels.Finance;
using GoatFarm.Domain.Enums;
using Microsoft.EntityFrameworkCore;

namespace GoatFarm.Infrastructure.Services;

public partial class FinanceService
{
    private sealed class PnlResult
    {
        public List<FinanceLineViewModel> IncomeLines { get; init; } = [];
        public List<FinanceLineViewModel> ExpenseLines { get; init; } = [];
        public decimal Income => IncomeLines.Sum(l => l.Amount);
        public decimal Expense => ExpenseLines.Sum(l => l.Amount);
        public decimal MilkIncome { get; init; }
        public decimal MilkLiters { get; init; }
        public decimal FeedUsed { get; init; }
        public decimal Medicine { get; init; }
        public decimal Vaccines { get; init; }
        public decimal Salaries { get; init; }
        public decimal Recurring { get; init; }
        public decimal ManualExpense { get; init; }
    }

    /// <summary>
    /// The one income/expense calculation. Every sale is counted once:
    /// Products › Sales by product name (milk included here only), Herd › GoatSales,
    /// manual Finance incomes (SourceType null), and invoices not generated by those sales.
    /// Legacy MilkSales are never income — use Products › Sales.
    /// </summary>
    private async Task<PnlResult> BuildPnlAsync(DateOnly from, DateOnly endExclusive, CancellationToken cancellationToken)
    {
        var months = PeriodMonths(from, endExclusive);

        var income = new Dictionary<string, decimal>(StringComparer.OrdinalIgnoreCase);
        void AddIncome(string label, decimal amount)
        {
            if (amount <= 0) return;
            income[label] = income.GetValueOrDefault(label) + amount;
        }

        var productRows = await _context.ProductSales.AsNoTracking()
            .Where(s => s.Date >= from && s.Date < endExclusive)
            .Select(s => new { s.ProductName, s.Qty, s.Amount })
            .ToListAsync(cancellationToken);
        foreach (var g in productRows.GroupBy(p => string.IsNullOrWhiteSpace(p.ProductName) ? "Product sales" : p.ProductName.Trim()))
            AddIncome(g.Key, g.Sum(x => x.Amount));

        var goatSalesTotal = await _context.GoatSales.AsNoTracking()
            .Where(s => s.Date >= from && s.Date < endExclusive)
            .SumAsync(s => (decimal?)s.Price, cancellationToken) ?? 0;
        AddIncome(FinanceIncomeRules.LiveGoatSaleLabel, goatSalesTotal);

        // Manual Cash received only — module-generated rows (GoatSale, etc.) are counted above.
        var incomeRows = await _context.Incomes.AsNoTracking()
            .Where(i => i.Date >= from && i.Date < endExclusive && i.SourceType == null)
            .Select(i => new { i.Type, i.Amount })
            .ToListAsync(cancellationToken);
        foreach (var g in incomeRows.GroupBy(i => i.Type))
            AddIncome(g.Key, g.Sum(x => x.Amount));

        var invoices = await _context.CustomerInvoices.AsNoTracking()
            .Where(i => i.Date >= from && i.Date < endExclusive && i.Status != InvoiceStatus.Void)
            .Select(i => new { i.Description, i.Amount })
            .ToListAsync(cancellationToken);
        AddIncome(FinanceIncomeRules.OtherFarmSaleLabel,
            invoices.Where(i => !FinanceIncomeRules.IsSaleGeneratedInvoice(i.Description)).Sum(i => i.Amount));

        var milkProducts = productRows.Where(p => FinanceIncomeRules.IsMilkProduct(p.ProductName)).ToList();

        var expense = new Dictionary<string, decimal>(StringComparer.OrdinalIgnoreCase);
        void AddExpense(string label, decimal amount)
        {
            if (amount <= 0) return;
            expense[label] = expense.GetValueOrDefault(label) + amount;
        }

        var feedUsed = await _feedService.GetFeedUsedCostAsync(from, endExclusive, cancellationToken);
        AddExpense("Feed used", feedUsed);
        var medicine = _feedService.CalculateFarmMedicineMonthly() * months;
        AddExpense("Medicine (plan)", medicine);
        var vaccines = await _context.VaccinePurchases.AsNoTracking()
            .Where(v => v.Date >= from && v.Date < endExclusive)
            .SumAsync(v => (decimal?)v.Amount, cancellationToken) ?? 0;
        AddExpense("Vaccines bought", vaccines);
        var staff = await _context.Employees.AsNoTracking().ToListAsync(cancellationToken);
        var salaries = endExclusive > from ? StaffSalaryAccrual.ForRange(staff, from, endExclusive.AddDays(-1)) : 0;
        AddExpense("Salaries", salaries);
        var recurringRows = await _context.RecurringCosts.AsNoTracking().ToListAsync(cancellationToken);
        decimal recurring = 0;
        foreach (var r in recurringRows)
        {
            var amount = (r.Period == RecurringCostPeriod.Year ? r.Amount / 12m : r.Amount) * months;
            recurring += amount;
            AddExpense(r.Name, amount);
        }
        var expenseRows = await _context.Expenses.AsNoTracking()
            .Where(e => e.Date >= from && e.Date < endExclusive)
            .Select(e => new { e.Type, e.Amount })
            .ToListAsync(cancellationToken);
        var manual = expenseRows.Where(e => !FinanceExpenseRules.IsDuplicateVaccinePurchase(e.Type)).ToList();
        foreach (var g in manual.GroupBy(e => e.Type))
            AddExpense(g.Key, g.Sum(x => x.Amount));

        return new PnlResult
        {
            IncomeLines = income.Select(kv => new FinanceLineViewModel { Label = kv.Key, Amount = kv.Value })
                .OrderByDescending(x => x.Amount).ToList(),
            ExpenseLines = expense.Select(kv => new FinanceLineViewModel { Label = kv.Key, Amount = kv.Value })
                .OrderByDescending(x => x.Amount).ToList(),
            MilkIncome = milkProducts.Sum(p => p.Amount),
            MilkLiters = milkProducts.Sum(p => p.Qty),
            FeedUsed = feedUsed,
            Medicine = medicine,
            Vaccines = vaccines,
            Salaries = salaries,
            Recurring = recurring,
            ManualExpense = manual.Sum(e => e.Amount)
        };
    }

    /// <summary>Whole calendar months count exactly; any other range is prorated by days.</summary>
    private static decimal PeriodMonths(DateOnly from, DateOnly endExclusive)
    {
        if (endExclusive <= from) return 0;
        if (from.Day == 1 && endExclusive.Day == 1)
            return (endExclusive.Year - from.Year) * 12 + endExclusive.Month - from.Month;
        var months = Math.Round((endExclusive.DayNumber - from.DayNumber) / 30.44m, 1);
        return months <= 0 ? 1 : months;
    }
}
